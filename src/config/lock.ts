import { readFile, writeFile } from "node:fs/promises";
import { parse, stringify } from "yaml";
import { z } from "zod";
import type { ProbePaths } from "./discovery";

const lockSchema = z.object({
  cliVersion: z.string(),
  makefile: z.object({ hash: z.string() }),
});

export type Lock = z.infer<typeof lockSchema>;

const HEADER = "# Generated by probe. Do not edit.\n";

export async function readLock(paths: ProbePaths): Promise<Lock | null> {
  try {
    const result = lockSchema.safeParse(parse(await readFile(paths.lock, "utf8")));
    return result.success ? result.data : null;
  } catch {
    return null;
  }
}

export async function writeLock(paths: ProbePaths, lock: Lock): Promise<void> {
  await writeFile(paths.lock, HEADER + stringify(lock));
}
