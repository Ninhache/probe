/** Closest ASCII for a glyph the screen draws; a character with none, or a braille dot, becomes `?` or `.`. */
export function asciiGlyph(ch: string): string {
  if (ch.charCodeAt(0) < 0x80) return ch;
  const code = ch.codePointAt(0) ?? 0;
  if (code >= 0x2800 && code <= 0x28ff) return ".";
  return GLYPHS[ch] ?? "?";
}
